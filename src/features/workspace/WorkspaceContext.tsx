'use client';
import { createContext, useCallback, useContext, useEffect, useRef, useState } from 'react';
import { useRouter } from 'next/navigation';
import {
  createConversation,
  getConversation,
  listConversations,
} from '@/features/chat/conversations-api';
import { useQuery, useQueryClient } from '@tanstack/react-query';
import { getProfile } from '@/features/profile/api';
import { ApiError, api, queryKeys } from '@/lib/api/client';
import type { Config, Conversation, Doc, Message, Source } from '@/lib/api/types';
import { listDocuments, uploadDocument, deleteDocument } from '@/features/documents/api';
import { completeChat } from '@/features/chat/api';
import { isInsufficientAnswer } from '@/features/chat/source-utils';
import { demoDocuments, demoConfig, demoAnswer } from './demo';
function useWorkspaceState(preview: boolean, local: boolean) {
  const client = useQueryClient();
  const router = useRouter();
  const [examples, setExamples] = useState<Doc[]>(demoDocuments);
  const [selected, setSelected] = useState<string[]>([]);
  const [messages, setMessages] = useState<Message[]>([]);
  const [sourcesAreRetrieved, setSourcesAreRetrieved] = useState(false);
  const [uploadNotice, setUploadNotice] = useState<{
    name: string;
    status: 'processing' | 'ready' | 'error';
  } | null>(null);
  const [sources, setSources] = useState<Source[] | null>(null);
  const [activeSource, setActiveSource] = useState<string | null>(null);
  const [uploadOpen, setUploadOpen] = useState(false);
  const [settingsOpen, setSettingsOpen] = useState(false);
  const [scopeOpen, setScopeOpen] = useState(false);
  const [pending, setPending] = useState(false);
  const [chatError, setChatError] = useState('');
  const conversationVersion = useRef(0);
  const active = useRef<{ id: string; revision: number } | null>(null);
  const sendLock = useRef(false);
  const [activeId, setActiveId] = useState<string | null>(null);
  const [historyLoading, setHistoryLoading] = useState(false);
  const [historyError, setHistoryError] = useState('');
  const [sending, setSending] = useState(false);
  const conversationsQuery = useQuery({
    queryKey: ['conversations'],
    queryFn: listConversations,
    enabled: !preview,
    refetchInterval: 15000,
  });
  const refreshConversations = useCallback(
    () => client.invalidateQueries({ queryKey: ['conversations'] }),
    [client],
  );
  const applyConversation = useCallback((conversation: Conversation) => {
    active.current = { id: conversation.id, revision: conversation.revision };
    setActiveId(conversation.id);
    setMessages(conversation.messages);
    setSelected(conversation.document_ids || []);
    setPending(conversation.pending);
    setChatError(conversation.error || '');
    setHistoryError('');
  }, []);
  const clear = useCallback(() => {
    conversationVersion.current += 1;
    active.current = null;
    sendLock.current = false;
    setActiveId(null);
    setMessages([]);
    setSelected([]);
    setSources(null);
    setUploadNotice(null);
    setSourcesAreRetrieved(false);
    setActiveSource(null);
    setPending(false);
    setSending(false);
    setChatError('');
    setHistoryError('');
    setHistoryLoading(false);
  }, []);
  const openConversation = useCallback(
    async (id: string | null, force = false) => {
      if (preview || (!force && (active.current?.id || null) === id)) return;
      clear();
      if (!id) return;
      const version = conversationVersion.current;
      active.current = { id, revision: 0 };
      setActiveId(id);
      setHistoryLoading(true);
      try {
        const conversation = await getConversation(id);
        if (version === conversationVersion.current) applyConversation(conversation);
      } catch (error) {
        if (version === conversationVersion.current)
          setHistoryError(error instanceof Error ? error.message : 'Could not load this chat.');
      } finally {
        if (version === conversationVersion.current) setHistoryLoading(false);
      }
    },
    [preview, clear, applyConversation],
  );
  // After refresh, observe an answer still being generated by the server.
  useEffect(() => {
    if (preview || !activeId || !pending || sending) return;
    const version = conversationVersion.current;
    let stopped = false;
    let fetching = false;
    const timer = window.setInterval(async () => {
      if (fetching) return;
      fetching = true;
      try {
        const conversation = await getConversation(activeId);
        if (!stopped && version === conversationVersion.current) {
          applyConversation(conversation);
          if (!conversation.pending) void refreshConversations();
        }
      } catch (error) {
        if (!stopped && version === conversationVersion.current)
          setHistoryError(error instanceof Error ? error.message : 'Could not sync this chat.');
      } finally {
        fetching = false;
      }
    }, 2000);
    return () => {
      stopped = true;
      window.clearInterval(timer);
    };
  }, [preview, activeId, pending, sending, applyConversation, refreshConversations]);
  const documentsQuery = useQuery({
    queryKey: queryKeys.documents,
    queryFn: listDocuments,
    enabled: !preview,
    refetchInterval: preview ? false : 15000,
  });
  const sessionQuery = useQuery({
    queryKey: ['session'],
    queryFn: getProfile,
    enabled: !preview && !local,
  });
  const configQuery = useQuery({
    queryKey: queryKeys.config,
    queryFn: () => api<Config>('v1/config'),
    enabled: !preview,
  });
  const healthQuery = useQuery({
    queryKey: queryKeys.health,
    queryFn: () => api<{ status: string }>('health'),
    enabled: !preview,
    refetchInterval: 30000,
  });
  const docs = preview ? examples : documentsQuery.data?.documents || [];
  const readinessQuery = useQuery({
    queryKey: queryKeys.ready,
    queryFn: () => api<{ status: 'ready'; components: Record<string, string> }>('ready'),
    enabled: !preview,
    refetchInterval: 30000,
  });
  const selectedIds = selected;
  const scopeInvalid = selected.some(
    (id) => !docs.some((d) => d.document_id === id && d.status === 'ready'),
  );
  const refresh = () => client.invalidateQueries({ queryKey: queryKeys.documents });
  const uploadFile = async (file: File) => {
    if (!preview) {
      const result = await uploadDocument(file);
      await refresh();
      return result;
    }
    const id = `example-${crypto.randomUUID()}`;
    setExamples((current) => [
      ...current,
      {
        document_id: id,
        file_name: file.name,
        file_type: file.name.split('.').pop() || '',
        size_bytes: file.size,
        num_chunks: 0,
        ingested_at: new Date().toISOString(),
        status: 'ready',
      },
    ]);
    return { document_id: id, status: 'success' as const };
  };
  const upload = async (file: File) => {
    setUploadNotice({ name: file.name, status: 'processing' });
    try {
      const result = await uploadFile(file);
      setUploadNotice({ name: file.name, status: 'ready' });
      return result;
    } catch (error) {
      setUploadNotice({ name: file.name, status: 'error' });
      throw error;
    }
  };
  const openSources = (message: Message, sourceId = message.sources?.[0]?.source_id) => {
    if (!sourceId) return;
    setSources(message.sources || []);
    setSourcesAreRetrieved(isInsufficientAnswer(message.content));
    setActiveSource(sourceId);
  };
  const remove = async (id: string) => {
    if (preview) setExamples((current) => current.filter((d) => d.document_id !== id));
    else {
      await deleteDocument(id);
      await refresh();
    }
    // Preserve explicit scope until the reader chooses a replacement.
  };
  const sendMessage = async (content: string, retry = false) => {
    if (sendLock.current || pending || historyLoading || historyError) return false;
    if (scopeInvalid || selectedIds.length > 100) {
      setChatError('Choose available documents before asking.');
      return false;
    }
    const history: Message[] = retry ? messages : [...messages, { role: 'user', content }];
    if (!history.length || history.at(-1)?.role !== 'user') return false;
    if (history.length > 32 || history.reduce((n, m) => n + m.content.length, 0) > 24000) {
      setChatError('This conversation has reached its limit. Start a new chat to continue.');
      return false;
    }
    const version = conversationVersion.current;
    const ids = [...selectedIds];
    let target = active.current;
    let accepted = true;
    sendLock.current = true;
    setPending(true);
    setSending(true);
    setChatError('');
    setMessages(history);
    try {
      if (preview) {
        const doc = docs.find((d) =>
          ids.length ? ids.includes(d.document_id) : d.status === 'ready',
        );
        if (!doc) throw new Error('Add an example document first.');
        const result = demoAnswer(doc);
        if (version === conversationVersion.current)
          setMessages([
            ...history,
            { role: 'assistant', content: result.content, sources: result.sources },
          ]);
      } else {
        if (!target) {
          const created = await createConversation();
          target = { id: created.id, revision: created.revision };
          if (version === conversationVersion.current) {
            active.current = target;
            setActiveId(target.id);
            router.replace('/chat?conversation=' + target.id, { scroll: false });
          }
        }
        await completeChat(history.slice(-1), ids, target);
        const saved = await getConversation(target.id);
        if (version === conversationVersion.current) applyConversation(saved);
      }
    } catch (error) {
      accepted = false;
      if (version === conversationVersion.current) {
        if (!preview && target) {
          // The request may have reached the server even if the response was lost.
          try {
            const saved = await getConversation(target.id);
            if (version === conversationVersion.current) {
              applyConversation(saved);
              const completed =
                saved.revision > target.revision &&
                saved.messages.at(-1)?.role === 'assistant' &&
                !(error instanceof ApiError && error.status === 409);
              if (saved.pending || completed) accepted = true;
              else {
                if (!saved.messages.length) setMessages(history);
                setChatError(
                  error instanceof Error ? error.message : 'Could not complete the answer.',
                );
              }
            }
          } catch {
            if (version === conversationVersion.current)
              setHistoryError('Could not sync this chat. Reopen it before sending again.');
          }
        } else setChatError(error instanceof Error ? error.message : 'Could not save this chat.');
      }
    } finally {
      if (!preview) void refreshConversations();
      if (version === conversationVersion.current) {
        sendLock.current = false;
        setSending(false);
        if (preview || !target) setPending(false);
      }
    }
    return accepted;
  };
  return {
    preview,
    local,
    uploadNotice,
    setUploadNotice,
    openSources,
    sourcesAreRetrieved,
    scopeInvalid,
    readinessQuery,
    sessionQuery,
    base: preview ? '/preview' : '',
    docs,
    config: preview ? demoConfig : configQuery.data,
    documentsQuery,
    configQuery,
    healthQuery,
    selectedIds,
    setSelected,
    messages,
    setMessages,
    sources,
    setSources,
    activeSource,
    setActiveSource,
    uploadOpen,
    setUploadOpen,
    settingsOpen,
    setSettingsOpen,
    scopeOpen,
    setScopeOpen,
    upload,
    remove,
    sendMessage,
    activeId,
    openConversation,
    historyLoading,
    historyError,
    conversationsQuery,
    refreshConversations,
    clear,
    refresh,
    pending,
    setPending,
    chatError,
    setChatError,
    conversationVersion,
  };
}
type Workspace = ReturnType<typeof useWorkspaceState>;
const Context = createContext<Workspace | null>(null);
export function WorkspaceProvider({
  children,
  preview = false,
  local = false,
}: {
  children: React.ReactNode;
  preview?: boolean;
  local?: boolean;
}) {
  const state = useWorkspaceState(preview, local);
  return <Context.Provider value={state}>{children}</Context.Provider>;
}
export function useWorkspace() {
  const value = useContext(Context);
  if (!value) throw new Error('Workspace provider required');
  return value;
}
